using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

#pragma warning disable RS1035 // Allow scanning GodotProjectDir for Assets-as-Code (VTX.Res) generation

namespace Godot.SourceGenerators
{
    [Generator]
    public sealed class TxFieldGenerator : ISourceGenerator
    {
        public void Initialize(GeneratorInitializationContext context)
        {
        }

        public void Execute(GeneratorExecutionContext context)
        {
            if (context.IsGodotToolsProject())
                return;

            GenerateTxFieldClasses(context);
            GenerateAssetRegistry(context);
        }

        private static void GenerateTxFieldClasses(GeneratorExecutionContext context)
        {
            var specs = new List<FieldSpec>();
            var invariantMethodsByType = new Dictionary<string, List<string>>();

            foreach (var tree in context.Compilation.SyntaxTrees)
            {
                var model = context.Compilation.GetSemanticModel(tree);
                var root = tree.GetRoot(context.CancellationToken);

                foreach (var fieldDecl in root.DescendantNodes().OfType<FieldDeclarationSyntax>())
                {
                    if (fieldDecl.AttributeLists.Count == 0)
                        continue;

                    foreach (var declarator in fieldDecl.Declaration.Variables)
                    {
                        if (model.GetDeclaredSymbol(declarator, context.CancellationToken) is not IFieldSymbol fieldSymbol)
                            continue;

                        var spec = TryCreateFieldSpec(fieldSymbol);
                        if (spec != null)
                        {
                            specs.Add(spec);
                        }
                    }
                }

                foreach (var methodDecl in root.DescendantNodes().OfType<MethodDeclarationSyntax>())
                {
                    if (methodDecl.AttributeLists.Count == 0)
                        continue;

                    if (model.GetDeclaredSymbol(methodDecl, context.CancellationToken) is not IMethodSymbol methodSymbol)
                        continue;

                    if (!HasTxInvariantAttribute(methodSymbol))
                        continue;

                    var containingType = methodSymbol.ContainingType;
                    if (containingType == null)
                        continue;

                    string typeFullName = containingType.ToDisplayString();
                    if (!invariantMethodsByType.TryGetValue(typeFullName, out var list))
                    {
                        list = new List<string>();
                        invariantMethodsByType[typeFullName] = list;
                    }
                    if (!list.Contains(methodSymbol.Name))
                    {
                        list.Add(methodSymbol.Name);
                    }
                }
            }

            if (specs.Count == 0)
                return;

            var groups = specs.GroupBy(s => s.ContainingTypeFullName);
            foreach (var group in groups)
            {
                var first = group.First();
                var fields = group.ToList();
                invariantMethodsByType.TryGetValue(first.ContainingTypeFullName, out var invariantMethods);

                string schemaSig = first.TypeName + "|" + string.Join("|", fields.Select(f => $"{f.PropertyName}:{f.ShortTypeName}"));

                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("#nullable enable");
                if (!string.IsNullOrEmpty(first.Namespace))
                {
                    sb.Append("namespace ").Append(first.Namespace).AppendLine();
                    sb.AppendLine("{");
                }

                sb.Append("partial class ").Append(first.TypeName).AppendLine(" : global::VTX.ITxObject");
                sb.AppendLine("{");

                sb.Append("    public const string TxSchemaSignature = \"").Append(schemaSig).AppendLine("\";");
                sb.AppendLine();

                // 1. Generated transactional properties
                foreach (var field in fields)
                {
                    sb.Append("    public ").Append(field.FieldTypeFullName).Append(' ').Append(field.PropertyName).AppendLine();
                    sb.AppendLine("    {");
                    sb.Append("        [global::VTX.Pure] get => this.").Append(field.FieldName).AppendLine(";");
                    sb.AppendLine("        [global::VTX.Transacts] set");
                    sb.AppendLine("        {");
                    sb.Append("            var prev = this.").Append(field.FieldName).AppendLine(";");
                    sb.Append("            if (!global::System.Collections.Generic.EqualityComparer<")
                      .Append(field.FieldTypeFullName)
                      .AppendLine(">.Default.Equals(prev, value))");
                    sb.AppendLine("            {");
                    sb.AppendLine("                if (global::VTX.Tx.IsActive)");
                    sb.AppendLine("                {");
                    sb.Append("                    global::VTX.Tx.Record(this, prev, static (owner, oldVal) => owner.")
                      .Append(field.FieldName)
                      .AppendLine(" = oldVal);");
                    sb.AppendLine("                }");
                    sb.Append("                this.").Append(field.FieldName).AppendLine(" = value;");
                    sb.AppendLine("            }");
                    sb.AppendLine("        }");
                    sb.AppendLine("    }");
                    sb.AppendLine();
                }

                // 2. Generated ITxObject.ValidateTxInvariants()
                sb.AppendLine("    [global::VTX.Decides]");
                sb.AppendLine("    void global::VTX.ITxObject.ValidateTxInvariants()");
                sb.AppendLine("    {");
                if (invariantMethods != null)
                {
                    foreach (var invMethod in invariantMethods)
                    {
                        sb.Append("        this.").Append(invMethod).AppendLine("();");
                    }
                }
                sb.AppendLine("    }");
                sb.AppendLine();

                // 3. Generated strongly-typed TxSnapshot + CaptureTxSnapshot / RestoreTxSnapshot / DiffTxState
                sb.Append("    public readonly record struct ").Append(first.TypeName).AppendLine("TxSnapshot(");
                for (int i = 0; i < fields.Count; i++)
                {
                    var f = fields[i];
                    sb.Append("        ").Append(f.FieldTypeFullName).Append(' ').Append(f.PropertyName);
                    sb.AppendLine(i + 1 < fields.Count ? "," : ");");
                }
                sb.AppendLine();

                sb.Append("    [global::VTX.Pure] public ").Append(first.TypeName).AppendLine("TxSnapshot CaptureTxSnapshot() => new(");
                for (int i = 0; i < fields.Count; i++)
                {
                    var f = fields[i];
                    sb.Append("        this.").Append(f.FieldName);
                    sb.AppendLine(i + 1 < fields.Count ? "," : ");");
                }
                sb.AppendLine();

                sb.AppendLine("    [global::VTX.Transacts]");
                sb.Append("    public void RestoreTxSnapshot(").Append(first.TypeName).AppendLine("TxSnapshot snapshot)");
                sb.AppendLine("    {");
                foreach (var f in fields)
                {
                    sb.Append("        this.").Append(f.PropertyName).Append(" = snapshot.").Append(f.PropertyName).AppendLine(";");
                }
                sb.AppendLine("    }");
                sb.AppendLine();

                // 4. Generated JSON Persistence (ToTxJson / FromTxJson)
                sb.AppendLine("    [global::VTX.Pure]");
                sb.AppendLine("    public string ToTxJson() => global::System.Text.Json.JsonSerializer.Serialize(this.CaptureTxSnapshot());");
                sb.AppendLine();

                sb.AppendLine("    [global::VTX.Decides]");
                sb.AppendLine("    public void FromTxJson(string json)");
                sb.AppendLine("    {");
                sb.Append("        var snap = global::System.Text.Json.JsonSerializer.Deserialize<")
                  .Append(first.TypeName).AppendLine("TxSnapshot>(json);");
                sb.AppendLine("        this.RestoreTxSnapshot(snap);");
                sb.AppendLine("    }");
                sb.AppendLine();

                // 5. Generated DiffTxState
                sb.AppendLine("    [global::VTX.Pure]");
                sb.Append("    public string DiffTxState(").Append(first.TypeName).AppendLine("TxSnapshot before)");
                sb.AppendLine("    {");
                sb.AppendLine("        var sb = new global::System.Text.StringBuilder();");
                foreach (var f in fields)
                {
                    sb.Append("        if (!global::System.Collections.Generic.EqualityComparer<")
                      .Append(f.FieldTypeFullName)
                      .Append(">.Default.Equals(before.")
                      .Append(f.PropertyName)
                      .Append(", this.")
                      .Append(f.FieldName)
                      .AppendLine("))");
                    sb.AppendLine("        {");
                    sb.AppendLine("            if (sb.Length > 0) sb.Append(\", \");");
                    sb.Append("            sb.Append(\"").Append(f.PropertyName).Append(": \").Append(before.")
                      .Append(f.PropertyName).Append(").Append(\" -> \").Append(this.").Append(f.FieldName).AppendLine(");");
                    sb.AppendLine("        }");
                }
                sb.AppendLine("        return sb.Length == 0 ? \"(no changes)\" : sb.ToString();");
                sb.AppendLine("    }");

                sb.AppendLine("}");
                if (!string.IsNullOrEmpty(first.Namespace))
                {
                    sb.AppendLine("}");
                }

                string hintName = first.ContainingTypeFullName.SanitizeQualifiedNameForUniqueHint() + "_TxFields.generated.cs";
                context.AddSource(hintName, SourceText.From(sb.ToString(), Encoding.UTF8));
            }
        }

        private static void GenerateAssetRegistry(GeneratorExecutionContext context)
        {
            string? projectDir = TryGetGodotProjectDir(context);
            if (string.IsNullOrEmpty(projectDir) || !Directory.Exists(projectDir))
                return;

            var scenes = new List<(string relPath, string resUrl)>();
            var shaders = new List<(string relPath, string resUrl)>();
            var textures = new List<(string relPath, string resUrl)>();
            var resources = new List<(string relPath, string resUrl)>();
            var audio = new List<(string relPath, string resUrl)>();
            var scripts = new List<(string relPath, string resUrl)>();

            ScanProjectAssets(projectDir!, projectDir!, scenes, shaders, textures, resources, audio, scripts);

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("namespace VTX");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// 编译期自动扫描项目目录生成的强类型资源清单（Assets as Code）。");
            sb.AppendLine("    /// 消除手写 \"res://...\" 字符串拼写错误；任何被删除或改名的资源会在编译期直接报错。");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public static class Res");
            sb.AppendLine("    {");

            EmitAssetCategory(sb, "Scenes", scenes);
            EmitAssetCategory(sb, "Shaders", shaders);
            EmitAssetCategory(sb, "Textures", textures);
            EmitAssetCategory(sb, "Resources", resources);
            EmitAssetCategory(sb, "Audio", audio);
            EmitAssetCategory(sb, "Scripts", scripts);

            sb.AppendLine("    }");
            sb.AppendLine("}");

            context.AddSource("VTX_Res.generated.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        private static void ScanProjectAssets(
            string rootDir,
            string currentDir,
            List<(string relPath, string resUrl)> scenes,
            List<(string relPath, string resUrl)> shaders,
            List<(string relPath, string resUrl)> textures,
            List<(string relPath, string resUrl)> resources,
            List<(string relPath, string resUrl)> audio,
            List<(string relPath, string resUrl)> scripts)
        {
            string[] files;
            try
            {
                files = Directory.GetFiles(currentDir);
            }
            catch
            {
                return;
            }

            foreach (var file in files)
            {
                string ext = Path.GetExtension(file).ToLowerInvariant();
                if (ext is ".uid" or ".import" or ".cs" or ".csproj" or ".sln" or ".cfg" or ".godot")
                    continue;

                string rel = file.Substring(rootDir.Length).TrimStart('\\', '/').Replace('\\', '/');
                string resUrl = "res://" + rel;

                switch (ext)
                {
                    case ".tscn":
                    case ".scn":
                        scenes.Add((rel, resUrl));
                        break;
                    case ".gdshader":
                    case ".shader":
                        shaders.Add((rel, resUrl));
                        break;
                    case ".svg":
                    case ".png":
                    case ".jpg":
                    case ".jpeg":
                    case ".webp":
                        textures.Add((rel, resUrl));
                        break;
                    case ".tres":
                    case ".res":
                        resources.Add((rel, resUrl));
                        break;
                    case ".wav":
                    case ".ogg":
                    case ".mp3":
                        audio.Add((rel, resUrl));
                        break;
                    case ".gd":
                        scripts.Add((rel, resUrl));
                        break;
                }
            }

            string[] subDirs;
            try
            {
                subDirs = Directory.GetDirectories(currentDir);
            }
            catch
            {
                return;
            }

            foreach (var subDir in subDirs)
            {
                string dirName = Path.GetFileName(subDir);
                if (dirName.StartsWith(".") ||
                    dirName.Equals("addons", StringComparison.OrdinalIgnoreCase) ||
                    dirName.Equals("bin", StringComparison.OrdinalIgnoreCase) ||
                    dirName.Equals("obj", StringComparison.OrdinalIgnoreCase) ||
                    dirName.Equals("analyzers", StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                ScanProjectAssets(rootDir, subDir, scenes, shaders, textures, resources, audio, scripts);
            }
        }

        private static void EmitAssetCategory(StringBuilder sb, string categoryName, List<(string relPath, string resUrl)> items)
        {
            sb.Append("        public static class ").Append(categoryName).AppendLine();
            sb.AppendLine("        {");

            var usedNames = new HashSet<string>(StringComparer.Ordinal);

            // Count short file names to expose short aliases when unambiguous
            var shortNameCounts = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
            foreach (var (relPath, _) in items)
            {
                string shortId = SanitizeIdentifier(Path.GetFileNameWithoutExtension(relPath));
                shortNameCounts.TryGetValue(shortId, out int c);
                shortNameCounts[shortId] = c + 1;
            }

            foreach (var (relPath, resUrl) in items.OrderBy(x => x.relPath, StringComparer.Ordinal))
            {
                string withoutExt = Path.ChangeExtension(relPath, null) ?? relPath;
                string fullId = SanitizeIdentifier(withoutExt);
                if (usedNames.Add(fullId))
                {
                    sb.Append("            public const string ").Append(fullId).Append(" = \"").Append(resUrl).AppendLine("\";");
                }

                string shortId = SanitizeIdentifier(Path.GetFileNameWithoutExtension(relPath));
                if (shortNameCounts.TryGetValue(shortId, out int count) && count == 1 && usedNames.Add(shortId))
                {
                    sb.Append("            public const string ").Append(shortId).Append(" = \"").Append(resUrl).AppendLine("\";");
                }
            }

            sb.AppendLine("        }");
        }

        private static string SanitizeIdentifier(string raw)
        {
            var sb = new StringBuilder();
            bool capitalizeNext = true;

            foreach (char ch in raw)
            {
                if (char.IsLetterOrDigit(ch))
                {
                    if (sb.Length == 0 && char.IsDigit(ch))
                    {
                        sb.Append('_');
                    }
                    sb.Append(capitalizeNext ? char.ToUpperInvariant(ch) : ch);
                    capitalizeNext = false;
                }
                else
                {
                    if (ch is '/' or '\\')
                    {
                        sb.Append('_');
                    }
                    capitalizeNext = true;
                }
            }

            return sb.Length == 0 ? "Asset" : sb.ToString();
        }

        internal static string? TryGetGodotProjectDir(GeneratorExecutionContext context)
        {
            if (context.TryGetGlobalAnalyzerProperty("GodotProjectDirBase64", out string? b64) && !string.IsNullOrEmpty(b64))
            {
                try
                {
                    return Encoding.UTF8.GetString(Convert.FromBase64String(b64));
                }
                catch
                {
                }
            }

            if (context.TryGetGlobalAnalyzerProperty("GodotProjectDir", out string? dir) && !string.IsNullOrEmpty(dir))
            {
                return dir;
            }

            return null;
        }

        private static bool HasTxInvariantAttribute(IMethodSymbol methodSymbol)
        {
            foreach (var attr in methodSymbol.GetAttributes())
            {
                if (attr.AttributeClass?.Name is "TxInvariantAttribute" or "TxInvariant")
                    return true;
            }
            return false;
        }

        private static FieldSpec? TryCreateFieldSpec(IFieldSymbol fieldSymbol)
        {
            AttributeData? txAttr = null;
            foreach (var attr in fieldSymbol.GetAttributes())
            {
                if (attr.AttributeClass?.Name is "TxFieldAttribute" or "TxField")
                {
                    txAttr = attr;
                    break;
                }
            }

            if (txAttr == null)
                return null;

            var containingType = fieldSymbol.ContainingType;
            if (containingType == null)
                return null;

            string? customName = null;
            if (txAttr.ConstructorArguments.Length > 0 &&
                txAttr.ConstructorArguments[0].Value is string s &&
                !string.IsNullOrWhiteSpace(s))
            {
                customName = s;
            }

            string propName = customName ?? ComputePropertyName(fieldSymbol.Name);
            string ns = containingType.ContainingNamespace.IsGlobalNamespace
                ? string.Empty
                : containingType.ContainingNamespace.ToDisplayString();

            string typeFullName = fieldSymbol.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            string shortTypeName = fieldSymbol.Type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);

            return new FieldSpec(
                ns,
                containingType.Name,
                containingType.ToDisplayString(),
                fieldSymbol.Name,
                propName,
                typeFullName,
                shortTypeName);
        }

        internal static string ComputePropertyName(string fieldName)
        {
            string trimmed = fieldName;
            if (trimmed.StartsWith("m_") && trimmed.Length > 2)
                trimmed = trimmed.Substring(2);
            else if (trimmed.StartsWith("_") && trimmed.Length > 1)
                trimmed = trimmed.Substring(1);

            if (trimmed.Length == 0)
                return fieldName + "Prop";

            return char.ToUpperInvariant(trimmed[0]) + trimmed.Substring(1);
        }

        private sealed class FieldSpec
        {
            public string Namespace { get; }
            public string TypeName { get; }
            public string ContainingTypeFullName { get; }
            public string FieldName { get; }
            public string PropertyName { get; }
            public string FieldTypeFullName { get; }
            public string ShortTypeName { get; }

            public FieldSpec(
                string ns,
                string typeName,
                string containingTypeFullName,
                string fieldName,
                string propertyName,
                string fieldTypeFullName,
                string shortTypeName)
            {
                Namespace = ns;
                TypeName = typeName;
                ContainingTypeFullName = containingTypeFullName;
                FieldName = fieldName;
                PropertyName = propertyName;
                FieldTypeFullName = fieldTypeFullName;
                ShortTypeName = shortTypeName;
            }
        }
    }
