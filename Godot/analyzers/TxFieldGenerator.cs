using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Godot.SourceGenerators
{
    [Generator]
    public sealed class TxFieldGenerator : ISourceGenerator
    {
        public void Initialize(GeneratorInitializationContext context)
        {
        }

        public void Execute(GeneratorExecutionContext context)
        {
            if (context.IsGodotToolsProject())
                return;

            var specs = new List<FieldSpec>();
            var invariantMethodsByType = new Dictionary<string, List<string>>();

            foreach (var tree in context.Compilation.SyntaxTrees)
            {
                var model = context.Compilation.GetSemanticModel(tree);
                var root = tree.GetRoot(context.CancellationToken);

                foreach (var fieldDecl in root.DescendantNodes().OfType<FieldDeclarationSyntax>())
                {
                    if (fieldDecl.AttributeLists.Count == 0)
                        continue;

                    foreach (var declarator in fieldDecl.Declaration.Variables)
                    {
                        if (model.GetDeclaredSymbol(declarator, context.CancellationToken) is not IFieldSymbol fieldSymbol)
                            continue;

                        var spec = TryCreateFieldSpec(fieldSymbol);
                        if (spec != null)
                        {
                            specs.Add(spec);
                        }
                    }
                }

                foreach (var methodDecl in root.DescendantNodes().OfType<MethodDeclarationSyntax>())
                {
                    if (methodDecl.AttributeLists.Count == 0)
                        continue;

                    if (model.GetDeclaredSymbol(methodDecl, context.CancellationToken) is not IMethodSymbol methodSymbol)
                        continue;

                    if (!HasTxInvariantAttribute(methodSymbol))
                        continue;

                    var containingType = methodSymbol.ContainingType;
                    if (containingType == null)
                        continue;

                    string typeFullName = containingType.ToDisplayString();
                    if (!invariantMethodsByType.TryGetValue(typeFullName, out var list))
                    {
                        list = new List<string>();
                        invariantMethodsByType[typeFullName] = list;
                    }
                    if (!list.Contains(methodSymbol.Name))
                    {
                        list.Add(methodSymbol.Name);
                    }
                }
            }

            if (specs.Count == 0)
                return;

            var groups = specs.GroupBy(s => s.ContainingTypeFullName);
            foreach (var group in groups)
            {
                var first = group.First();
                var fields = group.ToList();
                invariantMethodsByType.TryGetValue(first.ContainingTypeFullName, out var invariantMethods);

                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("#nullable enable");
                if (!string.IsNullOrEmpty(first.Namespace))
                {
                    sb.Append("namespace ").Append(first.Namespace).AppendLine();
                    sb.AppendLine("{");
                }

                sb.Append("partial class ").Append(first.TypeName).AppendLine(" : global::VTX.ITxObject");
                sb.AppendLine("{");

                // 1. Generated transactional properties
                foreach (var field in fields)
                {
                    sb.Append("    public ").Append(field.FieldTypeFullName).Append(' ').Append(field.PropertyName).AppendLine();
                    sb.AppendLine("    {");
                    sb.Append("        [global::VTX.Pure] get => this.").Append(field.FieldName).AppendLine(";");
                    sb.AppendLine("        [global::VTX.Transacts] set");
                    sb.AppendLine("        {");
                    sb.Append("            var prev = this.").Append(field.FieldName).AppendLine(";");
                    sb.Append("            if (!global::System.Collections.Generic.EqualityComparer<")
                      .Append(field.FieldTypeFullName)
                      .AppendLine(">.Default.Equals(prev, value))");
                    sb.AppendLine("            {");
                    sb.AppendLine("                if (global::VTX.Tx.IsActive)");
                    sb.AppendLine("                {");
                    sb.Append("                    global::VTX.Tx.Record(this, prev, static (owner, oldVal) => owner.")
                      .Append(field.FieldName)
                      .AppendLine(" = oldVal);");
                    sb.AppendLine("                }");
                    sb.Append("                this.").Append(field.FieldName).AppendLine(" = value;");
                    sb.AppendLine("            }");
                    sb.AppendLine("        }");
                    sb.AppendLine("    }");
                    sb.AppendLine();
                }

                // 2. Generated ITxObject.ValidateTxInvariants()
                sb.AppendLine("    [global::VTX.Decides]");
                sb.AppendLine("    void global::VTX.ITxObject.ValidateTxInvariants()");
                sb.AppendLine("    {");
                if (invariantMethods != null)
                {
                    foreach (var invMethod in invariantMethods)
                    {
                        sb.Append("        this.").Append(invMethod).AppendLine("();");
                    }
                }
                sb.AppendLine("    }");
                sb.AppendLine();

                // 3. Generated strongly-typed TxSnapshot + CaptureTxSnapshot / RestoreTxSnapshot / DiffTxState
                sb.Append("    public readonly record struct ").Append(first.TypeName).AppendLine("TxSnapshot(");
                for (int i = 0; i < fields.Count; i++)
                {
                    var f = fields[i];
                    sb.Append("        ").Append(f.FieldTypeFullName).Append(' ').Append(f.PropertyName);
                    sb.AppendLine(i + 1 < fields.Count ? "," : ");");
                }
                sb.AppendLine();

                sb.Append("    [global::VTX.Pure] public ").Append(first.TypeName).AppendLine("TxSnapshot CaptureTxSnapshot() => new(");
                for (int i = 0; i < fields.Count; i++)
                {
                    var f = fields[i];
                    sb.Append("        this.").Append(f.FieldName);
                    sb.AppendLine(i + 1 < fields.Count ? "," : ");");
                }
                sb.AppendLine();

                sb.AppendLine("    [global::VTX.Transacts]");
                sb.Append("    public void RestoreTxSnapshot(").Append(first.TypeName).AppendLine("TxSnapshot snapshot)");
                sb.AppendLine("    {");
                foreach (var f in fields)
                {
                    sb.Append("        this.").Append(f.PropertyName).Append(" = snapshot.").Append(f.PropertyName).AppendLine(";");
                }
                sb.AppendLine("    }");
                sb.AppendLine();

                sb.AppendLine("    [global::VTX.Pure]");
                sb.Append("    public string DiffTxState(").Append(first.TypeName).AppendLine("TxSnapshot before)");
                sb.AppendLine("    {");
                sb.AppendLine("        var sb = new global::System.Text.StringBuilder();");
                foreach (var f in fields)
                {
                    sb.Append("        if (!global::System.Collections.Generic.EqualityComparer<")
                      .Append(f.FieldTypeFullName)
                      .Append(">.Default.Equals(before.")
                      .Append(f.PropertyName)
                      .Append(", this.")
                      .Append(f.FieldName)
                      .AppendLine("))");
                    sb.AppendLine("        {");
                    sb.AppendLine("            if (sb.Length > 0) sb.Append(\", \");");
                    sb.Append("            sb.Append(\"").Append(f.PropertyName).Append(": \").Append(before.")
                      .Append(f.PropertyName).Append(").Append(\" -> \").Append(this.").Append(f.FieldName).AppendLine(");");
                    sb.AppendLine("        }");
                }
                sb.AppendLine("        return sb.Length == 0 ? \"(no changes)\" : sb.ToString();");
                sb.AppendLine("    }");

                sb.AppendLine("}");
                if (!string.IsNullOrEmpty(first.Namespace))
                {
                    sb.AppendLine("}");
                }

                string hintName = first.ContainingTypeFullName.SanitizeQualifiedNameForUniqueHint() + "_TxFields.generated.cs";
                context.AddSource(hintName, SourceText.From(sb.ToString(), Encoding.UTF8));
            }
        }

        private static bool HasTxInvariantAttribute(IMethodSymbol methodSymbol)
        {
            foreach (var attr in methodSymbol.GetAttributes())
            {
                if (attr.AttributeClass?.Name is "TxInvariantAttribute" or "TxInvariant")
                    return true;
            }
            return false;
        }

        private static FieldSpec? TryCreateFieldSpec(IFieldSymbol fieldSymbol)
        {
            AttributeData? txAttr = null;
            foreach (var attr in fieldSymbol.GetAttributes())
            {
                if (attr.AttributeClass?.Name is "TxFieldAttribute" or "TxField")
                {
                    txAttr = attr;
                    break;
                }
            }

            if (txAttr == null)
                return null;

            var containingType = fieldSymbol.ContainingType;
            if (containingType == null)
                return null;

            string? customName = null;
            if (txAttr.ConstructorArguments.Length > 0 &&
                txAttr.ConstructorArguments[0].Value is string s &&
                !string.IsNullOrWhiteSpace(s))
            {
                customName = s;
            }

            string propName = customName ?? ComputePropertyName(fieldSymbol.Name);
            string ns = containingType.ContainingNamespace.IsGlobalNamespace
                ? string.Empty
                : containingType.ContainingNamespace.ToDisplayString();

            string typeFullName = fieldSymbol.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

            return new FieldSpec(
                ns,
                containingType.Name,
                containingType.ToDisplayString(),
                fieldSymbol.Name,
                propName,
                typeFullName);
        }

        internal static string ComputePropertyName(string fieldName)
        {
            string trimmed = fieldName;
            if (trimmed.StartsWith("m_") && trimmed.Length > 2)
                trimmed = trimmed.Substring(2);
            else if (trimmed.StartsWith("_") && trimmed.Length > 1)
                trimmed = trimmed.Substring(1);

            if (trimmed.Length == 0)
                return fieldName + "Prop";

            return char.ToUpperInvariant(trimmed[0]) + trimmed.Substring(1);
        }

        private sealed class FieldSpec
        {
            public string Namespace { get; }
            public string TypeName { get; }
            public string ContainingTypeFullName { get; }
            public string FieldName { get; }
            public string PropertyName { get; }
            public string FieldTypeFullName { get; }

            public FieldSpec(
                string ns,
                string typeName,
                string containingTypeFullName,
                string fieldName,
                string propertyName,
                string fieldTypeFullName)
            {
                Namespace = ns;
                TypeName = typeName;
                ContainingTypeFullName = containingTypeFullName;
                FieldName = fieldName;
                PropertyName = propertyName;
                FieldTypeFullName = fieldTypeFullName;
            }
        }
    }
}
